-- =====================================================================
-- 0007: the order feed for Ravit's CRM (GET /api/get_orders, brief of
-- 12 Nov 2026).
--   * orders.is_test     PayPal sandbox orders never reach the live feed;
--                        the test key returns only these.
--   * courses.service_no the permanent, digits-only course number the CRM
--                        uses as service_id.
--   * order_feed         every feed row, frozen the first time it is served,
--                        so a row never changes afterwards (rule 4) and its
--                        item_id (item_no) is never reused (rule 3).
-- Run after 0006, in the SQL editor of each database (dev, prod), BEFORE
-- deploying the code that uses it. Safe to re-run.
-- =====================================================================

-- ------------------------------------------------------------ test orders
-- Live PayPal has never been switched on (the site has only used sandbox
-- keys), so every PayPal order taken before this migration is a sandbox test.
-- Manual orders entered by an admin are real and stay live. The marking runs
-- only in the same run that creates the column, so re-running this file
-- later never touches real orders.
do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'orders' and column_name = 'is_test'
  ) then
    alter table orders add column is_test boolean not null default false;
    update orders set is_test = true where payment_method = 'paypal';
  end if;
end
$$;

-- --------------------------------------------------------- course number
alter table courses add column if not exists service_no bigint generated by default as identity;
create unique index if not exists courses_service_no_idx on courses (service_no);

-- ------------------------------------------------------- frozen feed rows
create table if not exists order_feed (
  item_no      bigint generated by default as identity (start with 1001) primary key,
  order_id     uuid not null references orders(id) on delete cascade,
  course_slug  text not null,
  is_test      boolean not null default false,
  row          jsonb not null,           -- the row exactly as first served
  created_at   timestamptz not null default now(),
  unique (order_id, course_slug)
);

create index if not exists order_feed_test_idx on order_feed (is_test, item_no);

-- Written only by the server (service role). Admins can read it.
alter table order_feed enable row level security;
grant select on order_feed to authenticated;
grant all on order_feed to service_role;

drop policy if exists "admins read order feed" on order_feed;
create policy "admins read order feed" on order_feed
  for select using (public.is_admin());
